import { COMMON_OUTPUT_RULES } from './shared'

const BASE_PROJECT_EXPERIENCE_OUTPUT_RULES = [
  ...COMMON_OUTPUT_RULES,
  '- 按“业务目标/技术挑战 → 关键行动 → 可验证结果”的叙事组织内容，避免只堆技术名词。',
  '- 技术点、专业术语、系统名词、量化指标统一使用 Markdown 加粗，例如 **GIS 热力图**、**异常检测模型**、**污染问题发现效率**。',
  '- 量化结果必须来自原文或条目补充信息；若缺少 before、after 或变化幅度，使用 `[量化指标待补：指标名称]`，禁止补出看似真实的数字。',
  '- 若有多段项目经历，必须按原始顺序分段输出，分段标题必须使用该段真实项目名称（可用 `### 项目名称` 格式），禁止使用“项目经历1、项目经历2”等编号标题。',
  '- 每个项目分段下固定包含两个小节：#### 项目介绍 和 #### 主要工作。',
  '- 若只有单段项目经历，可直接输出：### 项目介绍 和 ### 主要工作。',
  '- 不要重复输出项目名称、角色、时间、链接这些基础字段。',
  '- ### 项目介绍 必须单段单行输出（不要换行、不要分点），写清楚“服务对象 + 业务场景 + 核心能力 + 项目价值”。',
  '- ### 项目介绍 必须回答“为什么开发这个项目、给谁用、解决什么场景问题”，并明确写出“主要功能包括xxx、xxx等”。',
  '- ### 项目介绍 禁止出现“建设目标”这四个字。',
  '- ### 项目介绍 禁止使用加粗标记（`**`）。',
  '- ### 主要工作 使用列表输出，且每条必须单行，句首必须使用“负责…”，禁止使用“针对…”。',
  '- ### 主要工作 每条优先使用模板：负责{业务功能/模块}，基于{关键技术/方法}实现{核心动作/机制}，解决/支撑{具体场景}，带来{真实指标或工程结果}。',
  '- ### 主要工作 仅当原始内容明确提到问题、痛点或瓶颈时，才允许写“解决了xxx问题”；若原文未提到问题，改写为“支撑/实现/完善xxx能力”。',
  '- ### 主要工作 每条建议保留 1-3 处加粗，优先加粗：关键技术、核心机制、真实数字或待补指标名称；不要为了凑加粗而拆碎句子。',
  '- ### 主要工作 若使用“从A缩短/提升/降低至B”结构，A、B 和变化幅度必须都来自原文；缺任一项时写成“将**异常排查耗时**从**7天**缩短至**[量化指标待补：优化后耗时]**”，不要输出空值或半截占位。',
  '- ### 主要工作 可以写非数字结果，但必须具体到对象与价值，例如“支撑靶向治理”“提升污染热点定位准确性”“形成排口溯源闭环”，禁止只写“显著提升效率”。',
  '- 严禁输出内部占位符或渲染 token，例如 `@@BOLD_TOKEN_1@@`。',
]

export function getProjectExperienceOutputRules(projectNames?: string[]): string[] {
  const rules = [...BASE_PROJECT_EXPERIENCE_OUTPUT_RULES]
  const names = (projectNames ?? []).filter(Boolean)
  if (names.length > 1) {
    rules.push(`- 当前共有 ${names.length} 段项目经历，必须按顺序使用以下项目名称作为分段标题：${names.join('、')}。`)
  }
  return rules
}

export const projectExperienceOutputRules = getProjectExperienceOutputRules()
